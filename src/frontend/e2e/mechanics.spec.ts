 await expect(card(ana)).toBeVisible();await expect(card(updated)).toBeVisible()
 await page.screenshot({path:`test-results/mechanics-${testInfo.project.name}.png`,fullPage:testInfo.project.name==='desktop',scale:'css'})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
