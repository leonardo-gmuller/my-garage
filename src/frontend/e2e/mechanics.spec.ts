 await contact.getByLabel('Oficina',{exact:true}).fill('Auto elétrica de teste')
 await contact.getByRole('button',{name:'Salvar mecânico',exact:true}).click();await expect(contact).toBeHidden()
 await expect(service.getByLabel('Descrição',{exact:true})).toHaveValue('Serviço preenchido antes do contato')
