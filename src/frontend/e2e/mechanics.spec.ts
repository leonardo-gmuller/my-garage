 await archivedService.getByRole('button',{name:'Salvar serviço',exact:true}).click();await expect(archivedService).toBeHidden()
 await expect(page.locator('.record-mechanic')).toContainText(joao)
 await navigate('Mecânicos')
 await page.getByRole('combobox',{name:'Situação',exact:true}).click();await page.getByRole('option',{name:'Arquivados',exact:true}).click()
 await page.getByLabel('Buscar contato',{exact:true}).fill(updated);await page.getByRole('button',{name:'Buscar',exact:true}).click()
