test('paint touches only exterior panels and selection restores the current custom paint', async ({page}) => {
 test.skip(!hasLocalSaveiro,'Modelo local opcional não distribuído no repositório.')
 await page.goto('/')
 const result=await page.evaluate(async()=>{
  const imports=['/node_modules/three/examples/jsm/loaders/GLTFLoader.js','/src/features/three/modelConfig.ts','/src/features/three/vehiclePaint.ts','/src/features/three/materialSelection.ts','/src/features/three/saveiroSurfaces.ts']
  const [{GLTFLoader},{saveiroModel,validateMapping,groupForMesh},{VehiclePaint},{MaterialSelection},{SaveiroSurfaces}]=await Promise.all(imports.map(p=>import(/* @vite-ignore */p)))
  const [gltf,document]=await Promise.all([new GLTFLoader().loadAsync(saveiroModel.url),fetch(saveiroModel.mappingUrl).then(r=>r.json())])
  const groups=validateMapping(document),meshes:any[]=[]
  gltf.scene.traverse((m:any)=>{if(m.isMesh){const group=groupForMesh(m.name,groups);m.userData.groupName=group?.name;m.userData.componentKey=group?saveiroModel.componentGroups[group.name]:null;meshes.push(m)}})
  const before=meshes.map(m=>({mesh:m,material:m.material,json:JSON.stringify(m.material.toJSON()),geometry:m.geometry}))
  const surfaces=new SaveiroSurfaces();surfaces.apply(gltf.scene)
  const finished=meshes.map(m=>({mesh:m,material:m.material}))
  const appearance=(group:string,source:string)=>before.filter(s=>s.mesh.userData.groupName===group&&s.material.name===source).map(s=>s.mesh.material)
  const all=(materials:any[],predicate:(m:any)=>boolean)=>materials.length>0&&materials.every(predicate)
  const trim=all(appearance('Friso','preto__spec_1'),m=>m.color.getHexString()==='202225'&&m.roughness>.6)
  const rack=all(appearance('rack','preto__spec_1'),m=>m.color.getHexString()==='53585d'&&m.metalness>.6)
  const tires=all(appearance('wheel_1','__Burnt_Umber_1'),m=>m.color.getHexString()==='141517'&&m.metalness===0)
  const wheels=all(appearance('wheel_1','__DimGray_'),m=>m.color.getHexString()==='85898e'&&m.metalness>.8)
  const glass=all(appearance('windscre01','__Translucent_Glass_Gray_1').filter(m=>m.color.getHexString()==='171b1e'),m=>m.transparent&&m.opacity===.78&&m.roughness<.2&&!m.depthWrite)
  const lights=all(appearance('farol','__DimGray_'),m=>m.metalness>.9)&&all(appearance('lanterna','Rosso_Alfa'),m=>m.color.getHexString()==='a90916')
  const lensExceptions=before.filter(s=>['windscre01__ID4035__504','windscre01__ID4075__510'].includes(s.mesh.name)).every(s=>s.mesh.material.opacity===.22&&s.mesh.material.color.getHexString()==='a8b2ba')&&before.filter(s=>s.mesh.name==='windscre01__ID4051__507').every(s=>s.mesh.material.color.getHexString()==='a90916')
  const noInteriorChanges=before.filter(s=>['painel','banco','int','int2','cofre'].includes(s.mesh.userData.groupName)).every(s=>s.mesh.material===s.material)
  const surfaceMaterials=new Set(finished.filter((s,i)=>s.material!==before[i].material).map(s=>s.material))
  const sharedFinishes=surfaceMaterials.size<25
  const paint=new VehiclePaint();paint.capture(gltf.scene);paint.apply('#C0C0C0','Metallic')
  const painted=finished.filter(s=>s.mesh.material!==s.material)
  const whitelist=['chassis','bonnet_ok','door_rf_01','boot_ok','bump_fro01','bump_rea01']
  const eligibleOnly=painted.every(s=>whitelist.includes(s.mesh.userData.groupName)&&s.material.name==='Diego'&&!s.material.transparent)
  const silver=painted.every(s=>s.mesh.material.color.getHexString()==='c0c0c0'&&s.mesh.material.isMeshPhysicalMaterial&&s.mesh.material.metalness===.78&&s.mesh.material.roughness===.3&&s.mesh.material.clearcoat===.55)
  const unchanged=finished.filter(s=>!painted.includes(s)).every(s=>s.mesh.material===s.material)
  const paintedMaterials=painted.map(s=>s.mesh.material),selection=new MaterialSelection();selection.capture(gltf.scene);selection.select('body','door_rf_01')
  selection.dispose();paint.apply('#214B80','Metallic');selection.capture(gltf.scene);selection.select('body','door_rf_01');selection.select(null,null)
  const restoresCustomPaint=painted.every(s=>s.mesh.material.color.getHexString()==='214b80')
  const cached=painted.every((s,i)=>s.mesh.material===paintedMaterials[i])
  selection.dispose();paint.dispose()
  const restoresFinishes=finished.every(s=>s.mesh.material===s.material)
  surfaces.dispose()
  const originalSourceIntact=before.every(s=>s.mesh.material===s.material&&JSON.stringify(s.material.toJSON())===s.json&&s.mesh.geometry===s.geometry)
  return{painted:painted.length,eligibleOnly,silver,unchanged,restoresCustomPaint,cached,originalSourceIntact,trim,rack,tires,wheels,glass,lights,lensExceptions,noInteriorChanges,sharedFinishes,restoresFinishes}
 })
 expect(result).toEqual({painted:29,eligibleOnly:true,silver:true,unchanged:true,restoresCustomPaint:true,cached:true,originalSourceIntact:true,trim:true,rack:true,tires:true,wheels:true,glass:true,lights:true,lensExceptions:true,noInteriorChanges:true,sharedFinishes:true,restoresFinishes:true})
})

